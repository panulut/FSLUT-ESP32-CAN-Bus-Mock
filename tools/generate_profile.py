#!/usr/bin/env python3
"""Validate explicit vehicle definitions and generate an allocation-free C++ profile."""
import argparse
import json
import math
from pathlib import Path
import re
import sys
from file_utils import atomic_write


def require(condition, message):
    if not condition:
        raise ValueError(message)


def whole(value, lo, hi, name):
    require(type(value) is int and lo <= value <= hi, f"{name}: expected integer {lo}..{hi}")
    return value


def number(value, name):
    require(type(value) in (int, float) and math.isfinite(value), f"{name}: expected finite number")
    return float(value)


def generate(profile):
    require(isinstance(profile, dict), "profile must be an object")
    require(not set(profile) - {"description", "messages"}, "unknown profile field")
    messages = profile["messages"]
    require(isinstance(messages, list) and len(messages) <= 32, "expected at most 32 messages")
    lines = ["// Generated by tools/generate_profile.py. Do not edit.", "#pragma once",
             '#include "can_core.h"', "inline bool loadVehicleProfile(cansim::Simulator& sim) {"]
    seen_ids, seen_names = set(), set()
    for message in messages:
        require(isinstance(message, dict), "message must be an object")
        require(not set(message) - {"id", "dlc", "interval_ms", "default_data", "checksum",
                                    "checksum_source", "source", "signals"}, "unknown message field")
        mid = message["id"]
        require(isinstance(mid, str) and re.fullmatch(r"0x[0-9a-fA-F]+", mid), "id must be 0x hex")
        mid = int(mid, 16)
        whole(mid, 0, 0x7FF, "profile CAN ID")
        require(mid not in seen_ids, "duplicate message ID")
        seen_ids.add(mid)
        dlc = whole(message["dlc"], 0, 8, "dlc")
        interval = whole(message["interval_ms"], 1, 3600000, "interval_ms")
        data = message["default_data"]
        require(isinstance(data, list) and len(data) == dlc, "default_data must match DLC")
        for byte in data:
            whole(byte, 0, 255, "data byte")
        require(isinstance(message.get("source"), str) and bool(message["source"].strip()),
                "each message needs a protocol source")
        checksum = message["checksum"]
        require(checksum in ("none", "sum_id_dlc"), "unsupported checksum")
        if checksum != "none":
            require(dlc == 8 and isinstance(message.get("checksum_source"), str) and
                    bool(message["checksum_source"].strip()),
                    "checksum needs DLC 8 and an explicit verification source")
        enum = "None" if checksum == "none" else "SumIdDlc"
        payload = ", ".join(str(x) for x in data) or "0"
        lines.append(f"    if (!sim.add({{0x{mid:X}, {dlc}, {{{payload}}}, false, false}}, "
                     f"{interval}, cansim::Checksum::{enum})) return false;")
        occupied = set()
        for sig in message.get("signals", []):
            require(isinstance(sig, dict), "signal must be an object")
            require(not set(sig) - {"name", "byte", "width", "endian", "signed", "scale",
                                    "offset", "min", "max", "default", "rate_per_second"},
                    "unknown signal field")
            name = sig["name"]
            require(isinstance(name, str) and re.fullmatch(r"[A-Z][A-Z0-9_]{0,31}", name),
                    "signal name must match [A-Z][A-Z0-9_]{0,31}")
            require(name not in seen_names, "signal names must be globally unique")
            seen_names.add(name)
            byte = whole(sig["byte"], 0, 7, "signal byte")
            width = whole(sig["width"], 1, 4, "signal width")
            field = set(range(byte, byte + width))
            require(byte + width <= dlc - (checksum != "none"), "signal exceeds payload / checksum")
            require(not occupied & field, "overlapping signals")
            occupied |= field
            require(sig["endian"] in ("big", "little"), "endian must be big or little")
            require(type(sig["signed"]) is bool, "signed must be boolean")
            scale, offset = number(sig["scale"], "scale"), number(sig["offset"], "offset")
            require(scale != 0, "scale cannot be zero")
            low, high = number(sig["min"], "min"), number(sig["max"], "max")
            default = number(sig["default"], "default")
            rate = number(sig.get("rate_per_second", 0), "rate_per_second")
            require(low <= default <= high, "default outside min/max")
            bits = width * 8
            raw_low = -(1 << (bits - 1)) if sig["signed"] else 0
            raw_high = (1 << (bits - int(sig["signed"]))) - 1
            for physical in (low, high, default):
                raw = (physical - offset) / scale
                require(math.isfinite(raw) and raw_low <= raw <= raw_high,
                        "signal range is not representable")
            little = str(sig["endian"] == "little").lower()
            signed = str(sig["signed"]).lower()
            lines.append(f'    if (!sim.addSignal({{0x{mid:X}, "{name}", {byte}, {width}, '
                         f'{little}, {signed}, {scale!r}, {offset!r}, {low!r}, {high!r}, '
                         f'{default!r}, {rate!r}}})) return false;')
    require(len(seen_names) <= 64, "at most 64 signals")
    lines.extend(["    return true;", "}", ""])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("input", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    try:
        require(args.input.resolve() != args.output.resolve(), "input and output must differ")
        result = generate(json.loads(args.input.read_text(encoding="utf-8")))
        atomic_write(args.output, result)
        print(f"Wrote {args.output}")
        return 0
    except (OSError, ValueError, KeyError, TypeError, OverflowError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
